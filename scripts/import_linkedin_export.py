"""Import Floris's LinkedIn data export into the voice corpus.

Usage:
  python3 scripts/import_linkedin_export.py <export folder or csv files...>

Reads whichever of these it finds: Rich_Media.csv (posts with media), Shares.csv (all posts incl. text-only),
Comments.csv (his comments). De-duplicates, applies config/voice_sources.yaml (use / info_only / exclude), and writes:
  voice/corpus/floris_posts.jsonl   one record per post/comment with date, kind, use, text
  voice/corpus/floris_examples.md   the 'use' posts, newest first, for drafting prompts
  voice/corpus/import_report.md     counts and anything that needs a human look
Raw export files are NOT copied into the repo.
"""

import csv
import json
import re
import sys
from datetime import datetime
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "voice" / "corpus"
DATE_RE = re.compile(r"on (\w+ \d{1,2}, \d{4})")


def parse_date(text: str) -> str:
    text = (text or "").strip()
    m = DATE_RE.search(text)
    if m:
        return datetime.strptime(m.group(1), "%B %d, %Y").date().isoformat()
    for fmt in ("%Y-%m-%d %H:%M:%S", "%Y-%m-%d", "%m/%d/%y, %I:%M %p", "%m/%d/%Y"):
        try:
            return datetime.strptime(text[:len(fmt) + 6].strip(), fmt).date().isoformat()
        except ValueError:
            continue
    return text[:10]


def clean(text: str) -> str:
    text = (text or "").replace("\r\n", "\n").strip()
    return "" if text in ("-", "") else text


def read_csv(path: Path) -> list[dict]:
    with open(path, encoding="utf-8", errors="replace", newline="") as f:
        return list(csv.DictReader(f))


def load(paths: list[Path]) -> list[dict]:
    files = []
    for p in paths:
        files += sorted(p.glob("*.csv")) if p.is_dir() else [p]
    records = []
    for f in files:
        name = f.name.lower()
        rows = read_csv(f)
        if "rich_media" in name:
            for r in rows:
                t = clean(r.get("Media Description", ""))
                if t:
                    records.append({"date": parse_date(r.get("Date/Time", "")), "kind": "post", "text": t, "source": f.name})
        elif "shares" in name:
            for r in rows:
                t = clean(r.get("ShareCommentary", "") or r.get("Commentary", ""))
                if t:
                    records.append({"date": parse_date(r.get("Date", "")), "kind": "post", "text": t, "source": f.name,
                                    "link": r.get("ShareLink", "")})
        elif "comments" in name:
            for r in rows:
                t = clean(r.get("Message", ""))
                if t:
                    records.append({"date": parse_date(r.get("Date", "")), "kind": "comment", "text": t, "source": f.name})
    # de-duplicate (the same post can appear in Shares and Rich_Media)
    seen, out = set(), []
    for r in sorted(records, key=lambda r: r["date"], reverse=True):
        key = (r["kind"], re.sub(r"\W+", "", r["text"].lower())[:120])
        if key not in seen:
            seen.add(key)
            out.append(r)
    return out


def classify(records: list[dict]) -> None:
    rules = yaml.safe_load((ROOT / "config" / "voice_sources.yaml").read_text())
    exclude, info = set(map(str, rules.get("exclude", []))), set(map(str, rules.get("info_only", [])))
    for r in records:
        r["use"] = "exclude" if r["date"] in exclude else "info_only" if r["date"] in info else "use"


def main(argv: list[str]) -> int:
    if not argv:
        print(__doc__)
        return 1
    records = load([Path(a) for a in argv])
    classify(records)
    OUT.mkdir(parents=True, exist_ok=True)
    with open(OUT / "floris_posts.jsonl", "w") as f:
        for r in records:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    use = [r for r in records if r["use"] == "use"]
    ex = ["# Floris: example posts and comments (his own voice)", "",
          "Generated by `scripts/import_linkedin_export.py`. Only posts marked `use` in `config/voice_sources.yaml`.",
          "Note: the export replaces emoji, £ and curly quotes with '?'. Read '?' at a line end as an emoji.", ""]
    for r in use:
        ex += [f"## {r['date']} · {r['kind']}", "", r["text"], ""]
    (OUT / "floris_examples.md").write_text("\n".join(ex))
    counts = {k: sum(1 for r in records if r["use"] == k) for k in ("use", "info_only", "exclude")}
    garbled = sum(1 for r in records if "?" in r["text"])
    rep = ["# Import report", "", f"Records: {len(records)} ({sum(r['kind']=='post' for r in records)} posts, "
           f"{sum(r['kind']=='comment' for r in records)} comments)",
           f"- use: {counts['use']}", f"- info_only: {counts['info_only']}", f"- exclude: {counts['exclude']}",
           f"- records containing '?' (likely lost emoji/£): {garbled}", "",
           "Dates in config/voice_sources.yaml not found in this import: "
           + ", ".join(sorted(set(map(str, yaml.safe_load((ROOT / 'config' / 'voice_sources.yaml').read_text()).get('exclude', [])
                                    + yaml.safe_load((ROOT / 'config' / 'voice_sources.yaml').read_text()).get('info_only', [])))
                              - {r['date'] for r in records})) or "none"]
    (OUT / "import_report.md").write_text("\n".join(rep) + "\n")
    print("\n".join(rep))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
